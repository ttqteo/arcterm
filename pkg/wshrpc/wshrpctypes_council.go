// CouncilCommands are the Council: a panel of expert agents that reviews one feature in three rounds. The cockpit
// starts one from Setup, an agent with `wsh council start`; both read it back through Get and List and learn of every
// change from the council:changed event. A command that changes a council returns once the change is saved: the
// rounds run in wavesrv after it.
type CouncilCommands interface {
	CouncilStartCommand(ctx context.Context, data CommandCouncilStartData) (*council.Council, error)
	CouncilListCommand(ctx context.Context, data CommandCouncilListData) ([]*council.Council, error)
	CouncilGetCommand(ctx context.Context, data CommandCouncilIdData) (*council.Council, error)
	CouncilReplyCommand(ctx context.Context, data CommandCouncilReplyData) error
	CouncilAskTooCommand(ctx context.Context, data CommandCouncilAskTooData) error
	CouncilContinueCommand(ctx context.Context, data CommandCouncilContinueData) error
	CouncilDraftCommand(ctx context.Context, data CommandCouncilDraftData) error
	CouncilSummarizeCommand(ctx context.Context, data CommandCouncilIdData) error
	CouncilStopCommand(ctx context.Context, data CommandCouncilIdData) error
	CouncilDeleteCommand(ctx context.Context, data CommandCouncilIdData) error
	CouncilPinCommand(ctx context.Context, data CommandCouncilPinData) error
	CouncilRetryCommand(ctx context.Context, data CommandCouncilRetryData) error
	CouncilSuggestCommand(ctx context.Context, data CommandCouncilSuggestData) (*council.CouncilSuggestion, error)
	CouncilAutoGenerateCommand(ctx context.Context, data CommandCouncilAutoGenerateData) (*council.CouncilAutoGenerate, error)
	CouncilEstimateCommand(ctx context.Context, data CommandCouncilEstimateData) (*CouncilEstimateRtnData, error)
	CouncilSaveDocCommand(ctx context.Context, data CommandCouncilSaveDocData) (*CouncilSaveDocRtnData, error)
	CouncilRolesCommand(ctx context.Context) (*CouncilRolesRtnData, error)
	CouncilSaveGroupCommand(ctx context.Context, data council.CouncilGroup) error
	CouncilRateCommand(ctx context.Context, data CommandCouncilRateData) error
	CouncilThumbCommand(ctx context.Context, data CommandCouncilThumbData) error
	CouncilDirectionCommand(ctx context.Context, data CommandCouncilDirectionData) error
	CouncilBenchCommand(ctx context.Context, data CommandCouncilBenchData) (*CouncilBenchRtnData, error)
	CouncilBenchResultsCommand(ctx context.Context) (*CouncilBenchResultsRtnData, error)
	CouncilBenchStopCommand(ctx context.Context) (*CouncilBenchStopRtnData, error)
}

// CommandCouncilStartData starts a council. Id alone starts the saved not-run council of that id and every other
// field is ignored. Otherwise Experts is the panel (the coordinator last, as council.ExpertsFor builds it) and, when
// empty, the panel of Group. NotRun saves the council as not-run and starts nothing, for a start the token gate
// refused: Start council in the app runs it later. Mode is council.ModeReview or council.ModeBrainstorm (empty is
// review; any other word is refused) and ModeWhy the one-line reason it was picked. Rounds is how many rounds the seats
// answer before the summary, the ideas round included: 1 to 3, and 0 is the default 2. An Experts entry with Agent set
// seats that live agent, and a council with one holds every answer as a draft, unless ByAgent says an agent started it.
// Agents are the live tabs to seat: tab ids or unique prefixes, in seat order. wavesrv resolves them (an id that is not a
// live claude or pi tab fails the call) and seats them before the Experts. ByAgent is set by `wsh council start`: the
// council never holds an answer as a draft, agents seated or not.
type CommandCouncilStartData struct {
	Id          string                  `json:"id,omitempty"`
	Project     string                  `json:"project,omitempty"`
	Feature     string                  `json:"feature,omitempty"`
	Question    string                  `json:"question,omitempty"`
	Files       []string                `json:"files,omitempty"`
	Screenshots []string                `json:"screenshots,omitempty"`
	Group       string                  `json:"group,omitempty"`
	Experts     []council.CouncilExpert `json:"experts,omitempty"`
	Pause       bool                    `json:"pause,omitempty"`
	SessionId   string                  `json:"sessionid,omitempty"`
	NotRun      bool                    `json:"notrun,omitempty"`
	Mode        string                  `json:"mode,omitempty"`
	ModeWhy     string                  `json:"modewhy,omitempty"`
	Rounds      int                     `json:"rounds,omitempty"`
	Agents      []string                `json:"agents,omitempty"`
	ByAgent     bool                    `json:"byagent,omitempty"`
}

// CommandCouncilListData lists the councils of one project, newest first; an empty project lists them all.
type CommandCouncilListData struct {
	Project string `json:"project,omitempty"`
}

// CommandCouncilIdData names one council: Get, Summarize and Stop take it.
type CommandCouncilIdData struct {
	Id string `json:"id"`
}

// CommandCouncilPinData pins a council (Pinned true: the tree keeps it at the top of its project) or unpins it, in any
// state.
type CommandCouncilPinData struct {
	Id     string `json:"id"`
	Pinned bool   `json:"pinned"`
}

// CommandCouncilReplyData is the person's reply. ProposalId and ParentId empty is "Ask the whole council"; a
// ParentId answers that reply, else the proposal itself. Tools turns on Let them read files for the answers. Agents are
// the tab ids (or unique prefixes) of the live chats the message seats: they are seated before the message is posted, a
// gone or unseatable id fails the send, and an id named twice or already seated sits once. Attachments are the absolute
// paths of the images the person attached: each must be a file the composer kept under ~/.arc/attachments (one per
// upload folder), and a reply carrying any is stored and answered with Tools on, whatever Tools says. ToolsAuto is the
// composer's Auto switch for Let them read files, sent only when no image or @file locks it on: Tools then holds the
// composer's guess, and the router decides it for a message it takes up (a person's On or Off is ToolsAuto false).
type CommandCouncilReplyData struct {
	Id          string   `json:"id"`
	ProposalId  string   `json:"proposalid,omitempty"`
	ParentId    string   `json:"parentid,omitempty"`
	Text        string   `json:"text"`
	Tools       bool     `json:"tools,omitempty"`
	ToolsAuto   bool     `json:"toolsauto,omitempty"`
	Agents      []string `json:"agents,omitempty"`
	Attachments []string `json:"attachments,omitempty"`
}

// CommandCouncilAskTooData is Ask <seat> too: ReplyId is the person's whole-council reply the router sent to some seats,
// and ExpertId the seat on the panel that was not among them and now answers it too, under the same reply.
type CommandCouncilAskTooData struct {
	Id       string `json:"id"`
	ReplyId  string `json:"replyid"`
	ExpertId string `json:"expertid"`
}

// CommandCouncilContinueData resumes a council paused after round 1: Cut lists the proposals the person unticked
// and Question, when set, is asked of the whole council.
type CommandCouncilContinueData struct {
	Id       string   `json:"id"`
	Cut      []string `json:"cut,omitempty"`
	Question string   `json:"question,omitempty"`
}

// CommandCouncilDraftData settles one held draft of a council: ItemId is the id of the idea (P1) or reply (r3) and
// Action is "send" (the draft reaches the other seats as written), "edit" (Text replaces the draft and is sent) or
// "drop" (it reaches no one).
type CommandCouncilDraftData struct {
	Id     string `json:"id"`
	ItemId string `json:"itemid"`
	Action string `json:"action"`
	Text   string `json:"text,omitempty"`
}

// CommandCouncilRetryData reruns the failed call of one expert; the coordinator's is the synthesis. Model, when set,
// runs this retry on that model instead of the seat's own (sonnet, fable, a full id); the seat keeps its model. All
// reruns every failed seat but the coordinator in one run, the seats at once, instead of ExpertId's alone; Models then
// picks a seat's model for this retry, by expert id (a seat it leaves out retries on its own).
type CommandCouncilRetryData struct {
	Id       string            `json:"id"`
	ExpertId string            `json:"expertid,omitempty"`
	Model    string            `json:"model,omitempty"`
	All      bool              `json:"all,omitempty"`
	Models   map[string]string `json:"models,omitempty"`
}

// CommandCouncilSuggestData asks for Setup's suggestion: the files to read and the roles that fit the feature.
type CommandCouncilSuggestData struct {
	Project  string   `json:"project"`
	Feature  string   `json:"feature"`
	Question string   `json:"question,omitempty"`
	Files    []string `json:"files,omitempty"`
}

// CommandCouncilAutoGenerateData asks for Setup's Auto-generate: Project is the folder the call runs in and Agents the
// seated agents' tab ids, in seat order. Their recent conversations become the topic, one question and the mode.
type CommandCouncilAutoGenerateData struct {
	Project string   `json:"project"`
	Agents  []string `json:"agents"`
}

// CommandCouncilEstimateData prices a council. With Id and Followup (a count of experts) it prices a follow-up round
// of that many calls, Tools being Let them read files; with Id alone it prices what a saved council has left to run;
// otherwise it prices the whole of a new council of Experts, reading the size of Files under Project, over Rounds
// rounds (0 is the default 2). Agents are live tabs to seat, as CommandCouncilStartData.Agents: wavesrv resolves them
// and prices their seats before the Experts. On a follow-up (Id and Followup or Agents set) Agents instead names the
// chat answerers, each priced at its context. Routed, with Id, prices a whole-council message the router would take: one
// router call and one to two seats, as a range (CouncilEstimateRtnData.CallsMax and TokensMax); ToolsAuto then says Let
// them read files is on Auto, so the range spans a message that reads files and one that does not.
type CommandCouncilEstimateData struct {
	Project   string                  `json:"project,omitempty"`
	Files     []string                `json:"files,omitempty"`
	Experts   []council.CouncilExpert `json:"experts,omitempty"`
	Id        string                  `json:"id,omitempty"`
	Followup  int                     `json:"followup,omitempty"`
	Tools     bool                    `json:"tools,omitempty"`
	Rounds    int                     `json:"rounds,omitempty"`
	Agents    []string                `json:"agents,omitempty"`
	Routed    bool                    `json:"routed,omitempty"`
	ToolsAuto bool                    `json:"toolsauto,omitempty"`
}

// CouncilEstimateRtnData is council.CouncilEstimate on the wire: counted, not priced. AgentTokens is the share of
// Tokens the seated agents' turns take. CallsMax and TokensMax are set only for a range (a routed message): Calls and
// Tokens are its low end and these its high end.
type CouncilEstimateRtnData struct {
	Calls       int   `json:"calls"`
	Tokens      int64 `json:"tokens"`
	Minutes     int   `json:"minutes"`
	AgentTokens int64 `json:"agenttokens,omitempty"`
	CallsMax    int   `json:"callsmax,omitempty"`
	TokensMax   int64 `json:"tokensmax,omitempty"`
}

// CommandCouncilSaveDocData writes a council's Summary and Matrix as markdown. An empty Path is
// docs/council/YYYY-MM-DD-<feature>.md in the project; a relative Path is under the project, and a Path outside it
// is refused.
type CommandCouncilSaveDocData struct {
	Id   string `json:"id"`
	Path string `json:"path,omitempty"`
}

// CouncilSaveDocRtnData is the absolute path the document was written to.
type CouncilSaveDocRtnData struct {
	Path string `json:"path"`
}

// CouncilRolesRtnData is the role library and the groups, the built-ins with the person's councilroles.json applied.
type CouncilRolesRtnData struct {
	Roles  []council.CouncilExpert `json:"roles"`
	Groups []council.CouncilGroup  `json:"groups"`
}

// CommandCouncilRateData is the person's answer to "Was this useful?" on a council's report: Rating is
// council.RatingUseful or council.RatingNot. Any other word is refused. The rating stays on the council and joins the
// benchmark's results file with the council's harness version and mode; a later rating of the same council replaces the
// first in the table and leaves its line in the file.
type CommandCouncilRateData struct {
	Id     string `json:"id"`
	Rating string `json:"rating"`
}

// CommandCouncilThumbData is the person's like or dislike on one of a council's sent ideas or seat replies: Item is its
// id (P1, r3) and Thumb council.ThumbLike or council.ThumbDislike, or empty to take it back. Any other word, the
// person's own reply and a draft are refused. The seats' later prompts and the summary read it as the person's view.
type CommandCouncilThumbData struct {
	Id    string `json:"id"`
	Item  string `json:"item"`
	Thumb string `json:"thumb,omitempty"`
}

// CommandCouncilDirectionData is one move on a council's direction memory. Action is one of council.ActionSet,
// ActionPin, ActionEdit, ActionAccept, ActionDismiss, ActionSetAnyway, ActionDiscard and ActionUnpin; any other word is
// refused. Text is the direction for set, pin and edit, and From the idea (P3) or message (r7) a pin comes from. A set,
// pin or edit is checked against what the seats said before it is set: it is set, or held for the person to set anyway
// or discard.
type CommandCouncilDirectionData struct {
	Id     string `json:"id"`
	Action string `json:"action"`
	Text   string `json:"text,omitempty"`
	From   string `json:"from,omitempty"`
}

// CommandCouncilBenchData picks a benchmark: the cases (every case not retired when empty), the variants (council and
// team when empty; solo is named to run it) and how many runs of each case × variant (1 when 0). DryRun only plans it:
// it lists the runs and prices them, and starts nothing, so the caller can ask the Token burn gate before the real call.
type CommandCouncilBenchData struct {
	Cases    []string `json:"cases,omitempty"`
	Variants []string `json:"variants,omitempty"`
	Runs     int      `json:"runs,omitempty"`
	DryRun   bool     `json:"dryrun,omitempty"`
}

// CouncilBenchRtnData is a bench's plan: the runs in the order they go, their total estimate in tokens, and the cases
// left out for a missing project folder or key (one line each). A call without DryRun has started the bench in wavesrv
// when it returns it; the councils run one at a time and the results file takes each as it ends.
type CouncilBenchRtnData struct {
	Items    []bench.CouncilBenchPlanItem `json:"items"`
	Estimate int64                        `json:"estimate"`
	Skipped  []string                     `json:"skipped,omitempty"`
}

// CouncilBenchResultsRtnData is the results file read back: a row per harness version and variant for the bench runs,
// and per harness version and mode for the ratings, the newest version first, so one version's score is never read as
// another's. Verdict is the go / no-go on the council against the agent team, read from the cases tagged for that pass;
// it is left out when no case carries the tag, or the cases cannot be read.
type CouncilBenchResultsRtnData struct {
	Runs    []bench.CouncilBenchRow       `json:"runs"`
	Ratings []bench.CouncilBenchRatingRow `json:"ratings"`
	Verdict *bench.CouncilBenchDecision   `json:"verdict,omitempty"`
}

// CouncilBenchStopRtnData says whether a bench was running to stop.
type CouncilBenchStopRtnData struct {
	Stopped bool `json:"stopped"`
}

// CouncilChangedData is the data of the council:changed event: the council that was saved, and its project. Deleted
// says it was removed instead, so there is nothing to load back.
type CouncilChangedData struct {
	Id      string `json:"id"`
	Project string `json:"project"`
	Deleted bool   `json:"deleted,omitempty"`
}
